  <section class="space-y-4">
    <div class="flex items-center gap-2 pb-2 border-b border-slate-200 dark:border-slate-800">
      <span class="flex h-6 w-6 items-center justify-center rounded-lg bg-amber-100 dark:bg-amber-950 font-mono text-xs font-bold text-amber-700 dark:text-amber-300">1</span>
      <h4 class="text-base font-bold text-slate-900 dark:text-white">Hospital Personnel Acceptable Use Directives</h4>
    </div>
    <p>
      Pursuant to Section 3(A) and Section 17 of <strong>NPC Circular No. 2016-01</strong>, all hospital officers, billing staff, cashiers, accounting personnel, and medical social workers must strictly adhere to the following directives:
    </p>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-3 text-xs">
      <div class="p-3.5 rounded-xl border border-slate-200 bg-white dark:border-slate-800 dark:bg-slate-900 space-y-1.5">
        <span class="font-bold text-slate-900 dark:text-white flex items-center gap-1.5">
          <i class="ph-bold ph-identification-card text-emerald-600 dark:text-emerald-400"></i>
          1. Individual Attribution &amp; Non-Sharing
        </span>
        <p class="text-slate-600 dark:text-slate-400">
          Users must never disclose, write down, or share user IDs, passwords, or TOTP 2FA secret keys. Any transaction executed under an account is irrevocably attributed to the registered account owner.
        </p>
      </div>

      <div class="p-3.5 rounded-xl border border-slate-200 bg-white dark:border-slate-800 dark:bg-slate-900 space-y-1.5">
        <span class="font-bold text-slate-900 dark:text-white flex items-center gap-1.5">
          <i class="ph-bold ph-hard-drive text-rose-600 dark:text-rose-400"></i>
          2. No Local Extraction or Personal Storage
        </span>
        <p class="text-slate-600 dark:text-slate-400">
          Section 19 of NPC Circular 2016-01 explicitly prohibits copying, downloading, or exporting patient bills, financial reports, or ledger archives to unauthorized flash drives, external HDDs, or personal devices.
        </p>
      </div>

      <div class="p-3.5 rounded-xl border border-slate-200 bg-white dark:border-slate-800 dark:bg-slate-900 space-y-1.5">
        <span class="font-bold text-slate-900 dark:text-white flex items-center gap-1.5">
          <i class="ph-bold ph-desktop text-blue-600 dark:text-blue-400"></i>
          3. Authorized Workstations Only
        </span>
        <p class="text-slate-600 dark:text-slate-400">
          In compliance with Section 20 of NPC Circular 2016-01, access is restricted to pre-registered, government-owned, or hospital-authorized terminals protected by endpoint security and hardware UUID verification.
        </p>
      </div>

      <div class="p-3.5 rounded-xl border border-slate-200 bg-white dark:border-slate-800 dark:bg-slate-900 space-y-1.5">
        <span class="font-bold text-slate-900 dark:text-white flex items-center gap-1.5">
          <i class="ph-bold ph-user-switch text-purple-600 dark:text-purple-400"></i>
          4. Single Session &amp; Inactivity Auto-Lock
        </span>
        <p class="text-slate-600 dark:text-slate-400">
          Concurrent multi-terminal logins are blocked. Sessions automatically expire after 15 minutes of inactivity to protect unattended cashier terminals and billing desks from unauthorized use.
        </p>
      </div>
    </div>
  </section>

