  <!-- Section 3: COA Auditability, Immutable Logs & General Ledger Integrity -->
  <section id="tc-section-3" class="space-y-3">
    <div class="flex items-center gap-2 pb-2 border-b border-slate-200 dark:border-slate-800">
      <span class="flex h-6 w-6 items-center justify-center rounded-md border border-slate-200 dark:border-slate-700 bg-slate-100 dark:bg-slate-800 font-mono text-xs font-semibold text-slate-700 dark:text-slate-300">3</span>
      <h4 class="text-base font-bold tracking-tight text-slate-900 dark:text-white">Commission on Audit (COA) Auditing &amp; Ledger Immutability</h4>
    </div>
    <p>
      All financial transactions, patient invoices, journal vouchers, disbursement releases, cashier collections, and credit adjustments are subject to <strong>continuous, unannounced electronic auditing by the Commission on Audit (COA)</strong> pursuant to Presidential Decree No. 1445 and the Government Accounting Manual.
    </p>
    <ul class="list-disc pl-5 space-y-1.5 text-xs text-slate-600 dark:text-slate-400">
      <li><strong>Write-Once-Read-Many (WORM) Audit Trail:</strong> Every record mutation generates an immutable, tamper-evident audit record capturing the user ID, full name, timestamp, IP address, device UUID, and exact previous versus updated values with cryptographic SHA-256 hash chaining.</li>
      <li><strong>Double-Entry Invariance:</strong> In strict compliance with GAAP/IFRS and the Revised Chart of Accounts (RCA), no Journal Entry Voucher (JEV) can be saved or posted unless total debits exactly equal total credits (<code>sum(debit) === sum(credit)</code>).</li>
      <li><strong>Immutability of Posted Records:</strong> Posted transactions, issued Official Receipts (OR), and approved disbursement vouchers cannot be updated or deleted. Corrections must strictly be executed through compensating reversal entries (<code>REVERSED</code> status) and newly balanced offsetting vouchers.</li>
      <li><strong>Legal Force of Electronic Signatures:</strong> Signatures rendered electronically on JEVs, Budget Utilization Request and Status (BURS) forms, and Disbursement Vouchers (DV) carry full legal validity under Republic Act No. 8792 (Electronic Commerce Act of 2000) and the Philippine Supreme Court Rules on Electronic Evidence.</li>
    </ul>
  </section>

