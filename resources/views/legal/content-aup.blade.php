    <div class="rounded-xl border border-rose-200 bg-rose-50/60 p-4 dark:border-rose-900/60 dark:bg-rose-950/40 text-xs text-rose-950 dark:text-rose-200 space-y-2">
      <div class="font-bold text-sm text-rose-800 dark:text-rose-300 flex items-center gap-2">
        <i class="ph-bold ph-gavel text-base"></i>
        Republic Act No. 11463 (Malasakit Centers Act) &bull; Section 14 Penalties
      </div>
      <p class="leading-relaxed">
        <strong>Fraudulent Beneficiaries:</strong> Any individual who knowingly submits false information, conceals assets or income, or presents counterfeit barangay indigency certificates to obtain socialized medical assistance is legally required to pay <strong>DOUBLE (2x) the amount of financial assistance granted</strong>, and shall suffer <strong>criminal imprisonment of six (6) months to two (2) years</strong>.
      </p>
      <p class="leading-relaxed">
        <strong>Public Officers &amp; Staff:</strong> Any hospital employee, medical social worker, cashier, or accounting officer who misappropriates funds, facilitates fraudulent claims, or consents to unauthorized deductions shall be fined <strong>TRIPLE (3x) the amount misappropriated per count</strong>, face administrative termination, and suffer perpetual disqualification from public office, alongside prosecution under Republic Act No. 3019 (Anti-Graft and Corrupt Practices Act).
      </p>
