    </div>
    <p>
      The HFMS operates as a centralized consolidation and routing engine that integrates subsidies from PhilHealth (RA 11223), DOH-MAIP, DSWD-AICS, PCSO Guarantee Letters, and LGU assistance funds. Users acknowledge and agree that:
    </p>
    <ul class="list-disc pl-5 space-y-1.5 text-xs text-slate-600 dark:text-slate-400">
      <li><strong>Independent Agency Discretion:</strong> The final approval, partial approval, or rejection of assistance applications rests solely within the statutory discretion of the respective funding agencies (e.g. DSWD social workers for AICS or PCSO evaluation officers for GL allocations). The hospital functions exclusively as the aggregating and processing facility.</li>
      <li><strong>System Outage &amp; Delay Disclaimer:</strong> The hospital entity disclaims liability for delays in billing clearances, PhilHealth ACR calculations, or Guarantee Letter approvals resulting from external third-party API downtime, telecommunications outages, or incomplete patient submissions.</li>
      <li><strong>Unconditional Emergency Stabilization Guarantee:</strong> Pursuant to Republic Act No. 10932 (Anti-Hospital Deposit Law) and RA 11223, emergency medical treatment and stabilization shall <strong>NEVER be delayed or withheld</strong> due to HFMS system maintenance, network downtime, or pending financial aid reconciliation. Financial clearance will proceed post-stabilization.</li>
    </ul>
  </section>

