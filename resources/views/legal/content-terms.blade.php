    </p>
    <ul class="list-disc pl-5 space-y-1.5 text-xs text-slate-600 dark:text-slate-400">
      <li>Financial, billing, and budgetary records cannot be arbitrarily altered or purged. All records must be preserved for the statutory retention periods mandated by COA (minimum 10 years for journals and vouchers, permanent for general ledgers).</li>
      <li>The HFMS implements automated software blockers that prevent the soft-deletion, archiving, or disposal of any patient billing file, disbursement record, or voucher associated with an <strong>open COA audit disallowance (Notice of Disallowance / ND)</strong>, audit inquiry, or unresolved charge.</li>
      <li>Any authorized data destruction following statutory expiration must strictly follow NAP-certified disposal protocols with permanent retention of Certificates of Disposal.</li>
